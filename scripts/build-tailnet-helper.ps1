<#
.SYNOPSIS
    Builds the Go desk-tailnet-helper binary with stripped symbols, its icon and Task Manager name.
.DESCRIPTION
    Compiles apps/desk-tailnet-helper into desk-tailnet-helper.exe ready for embedding into the
    single DeskRemote-Ajan.exe executable. The Windows version resource (name, product, version
    from VERSION) and the icon are embedded as a .syso generated by goversioninfo; the name comes
    from crates/desk-exe-identity/identity.json (the one source for every executable, DAPP-121).
#>

[CmdletBinding()]
param()

$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $PSScriptRoot
$GoHelperDir = Join-Path $RepoRoot "apps\desk-tailnet-helper"
$GoVersionInfo = "github.com/josephspurrier/goversioninfo/cmd/goversioninfo@v1.4.1"

if (-not (Test-Path $GoHelperDir)) {
    Write-Error "apps/desk-tailnet-helper directory not found at $GoHelperDir"
    exit 1
}

$Identity = Get-Content (Join-Path $RepoRoot "crates\desk-exe-identity\identity.json") -Raw | ConvertFrom-Json
$Exe = $Identity.exes.tailnet
$Version = (Get-Content (Join-Path $RepoRoot "VERSION") -Raw).Trim()
if ($Version -notmatch '^(\d+)\.(\d+)\.(\d+)$') {
    Write-Error "VERSION '$Version' is not major.minor.patch"
    exit 1
}
$Icon = Join-Path $RepoRoot "apps\desk-service\icons\icon.ico"

Write-Host "Compiling $($Exe.file) ($($Exe.description) $Version) in $GoHelperDir..." -ForegroundColor Cyan
Push-Location $GoHelperDir
try {
    # goversioninfo needs a JSON file argument; every value comes from the flags below.
    $Empty = Join-Path $env:TEMP "desk-versioninfo-empty.json"
    Set-Content -Path $Empty -Value "{}" -Encoding ascii
    & go run $GoVersionInfo -64 -o rsrc_windows_amd64.syso `
        -description $Exe.description -product-name $Identity.product `
        -internal-name $Exe.file -original-name $Exe.file -copyright $Identity.copyright `
        -file-version $Version -product-version $Version `
        -ver-major $Matches[1] -ver-minor $Matches[2] -ver-patch $Matches[3] -ver-build 0 `
        -product-ver-major $Matches[1] -product-ver-minor $Matches[2] -product-ver-patch $Matches[3] -product-ver-build 0 `
        -icon $Icon $Empty
    if ($LASTEXITCODE -ne 0) {
        Write-Error "goversioninfo failed with exit code $LASTEXITCODE"
        exit 1
    }
    & go build -ldflags="-s -w" -o $Exe.file .
    if ($LASTEXITCODE -ne 0) {
        Write-Error "Go compilation failed with exit code $LASTEXITCODE"
        exit 1
    }
    $file = Get-Item $Exe.file
    Write-Host "Successfully built $($Exe.file) ($($file.Length) bytes)" -ForegroundColor Green
} finally {
    Pop-Location
}
