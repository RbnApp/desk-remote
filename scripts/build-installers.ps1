<#
.SYNOPSIS
    Builds the two Desk-Remote installers: panel (Tauri NSIS) and agent (NSIS), into dist\.
.DESCRIPTION
    One command: release build of panel, agent and the Windows 11 menu DLL, sparse package
    (signed with a locally created, non-exportable self-signed certificate), installer strings
    from locales/*.json, then
      dist\Desk-Remote-Panel-Setup-<VERSION>.exe
      dist\Desk-Remote-Ajan-Setup-<VERSION>.exe
      dist\SHA256SUMS.txt
    The installers themselves are NOT code-signed (no certificate is bought); Windows
    SmartScreen will warn on first run. The version comes only from the root VERSION file.
#>

[CmdletBinding()]
param()

$ErrorActionPreference = "Stop"

$RepoRoot = Split-Path -Parent $PSScriptRoot
Set-Location $RepoRoot

$Version = (Get-Content (Join-Path $RepoRoot "VERSION") -Raw).Trim()
$Version4 = "$Version.0"
$Dist = Join-Path $RepoRoot "dist"
$Work = Join-Path $RepoRoot "target\installer"
$Gen = Join-Path $RepoRoot "packaging\generated"
$Publisher = "CN=Desk-Remote Menu"
$Clsid = "7C1F5B2E-3D4A-4E8B-9A61-5D0E2F8B4C13"   # = CLSID_DESK_REMOTE_SEND in apps/desk-shell-ext

function Step([string]$Text) { Write-Host "`n== $Text" -ForegroundColor Cyan }
function Run([string]$What, [scriptblock]$Block) {
    & $Block
    if ($LASTEXITCODE -ne 0) { throw "$What failed (exit $LASTEXITCODE)" }
}

New-Item -ItemType Directory -Force $Dist, $Work, $Gen | Out-Null

# ---- Windows SDK tools (makeappx, signtool) ------------------------------------------------
$Kits = Get-ChildItem "${env:ProgramFiles(x86)}\Windows Kits\10\bin" -Directory -ErrorAction SilentlyContinue |
    Where-Object { Test-Path (Join-Path $_.FullName "x64\makeappx.exe") } |
    Sort-Object Name -Descending | Select-Object -First 1
if (-not $Kits) { throw "Windows SDK (makeappx.exe, signtool.exe) not found" }
$MakeAppx = Join-Path $Kits.FullName "x64\makeappx.exe"
$SignTool = Join-Path $Kits.FullName "x64\signtool.exe"

# ---- 1. Release build ----------------------------------------------------------------------
Step "Release build (agent, menu DLL; the panel is built by the Tauri bundler below)"
if (-not (Test-Path "apps\desk-tailnet-helper\desk-tailnet-helper.exe")) {
    Run "tailnet helper" { & powershell -NoProfile -File (Join-Path $PSScriptRoot "build-tailnet-helper.ps1") }
}
Run "cargo build" { & cargo build --release -p desk-service -p desk-shell-ext }

# ---- 2. Installer strings from locales (single source) -------------------------------------
Step "Installer strings from locales/en.json + locales/tr.json"
function NsisText([string]$Text) {
    return ($Text -replace '\$', '$$$$' -replace '"', '$\"' -replace "`r?`n", '$\n')
}
$En = (Get-Content (Join-Path $RepoRoot "locales\en.json") -Raw -Encoding UTF8 | ConvertFrom-Json).installer
$Tr = (Get-Content (Join-Path $RepoRoot "locales\tr.json") -Raw -Encoding UTF8 | ConvertFrom-Json).installer
$Lines = @("; Generated by scripts/build-installers.ps1 from locales/*.json - do not edit.")
foreach ($p in $En.PSObject.Properties) {
    $Lines += "!define STR_EN_$($p.Name) `"$(NsisText $p.Value)`""
    $Lines += "!define STR_TR_$($p.Name) `"$(NsisText $Tr.($p.Name))`""
}

# ---- 3. Package certificate (private key stays in this account's store, not exportable) ----
Step "Sparse-package certificate"
$Cert = Get-ChildItem Cert:\CurrentUser\My | Where-Object { $_.Subject -eq $Publisher -and $_.NotAfter -gt (Get-Date).AddMonths(6) } |
    Sort-Object NotAfter -Descending | Select-Object -First 1
if (-not $Cert) {
    $Cert = New-SelfSignedCertificate -Type Custom -Subject $Publisher -KeyUsage DigitalSignature `
        -FriendlyName "Desk-Remote Explorer menu package" -CertStoreLocation Cert:\CurrentUser\My `
        -KeyExportPolicy NonExportable -NotAfter (Get-Date).AddYears(10) `
        -TextExtension @("2.5.29.37={text}1.3.6.1.5.5.7.3.3", "2.5.29.19={text}")
    Write-Host "created certificate $($Cert.Thumbprint)"
} else {
    Write-Host "reusing certificate $($Cert.Thumbprint)"
}
$CerFile = Join-Path $Work "DeskRemote-Menu.cer"
Export-Certificate -Cert $Cert -FilePath $CerFile | Out-Null
$Lines += "!define MENU_CERT_SHA1 `"$($Cert.Thumbprint)`""
[IO.File]::WriteAllLines((Join-Path $Gen "installer-strings.nsh"), $Lines, (New-Object Text.UTF8Encoding $true))

# ---- 4. Sparse package ---------------------------------------------------------------------
Step "Sparse package DeskRemote-Menu.msix"
$Stage = Join-Path $Work "msix-stage"
if (Test-Path $Stage) { Remove-Item $Stage -Recurse -Force }
New-Item -ItemType Directory -Force (Join-Path $Stage "Assets") | Out-Null
$Icons = Join-Path $RepoRoot "apps\desk-panel\icons"
Copy-Item (Join-Path $Icons "32x32.png") (Join-Path $Stage "Assets\logo44.png")
Copy-Item (Join-Path $Icons "128x128.png") (Join-Path $Stage "Assets\logo150.png")
Copy-Item (Join-Path $Icons "128x128.png") (Join-Path $Stage "Assets\logo.png")
$Manifest = (Get-Content (Join-Path $RepoRoot "packaging\AppxManifest.xml.in") -Raw -Encoding UTF8).
    Replace("@PUBLISHER@", $Publisher).Replace("@VERSION4@", $Version4).Replace("@CLSID@", $Clsid)
[IO.File]::WriteAllText((Join-Path $Stage "AppxManifest.xml"), $Manifest, (New-Object Text.UTF8Encoding $false))
$Msix = Join-Path $Work "DeskRemote-Menu.msix"
Run "makeappx" { & $MakeAppx pack /d $Stage /p $Msix /nv /o | Out-Host }
Run "signtool" { & $SignTool sign /fd SHA256 /sha1 $Cert.Thumbprint $Msix | Out-Host }

# ---- 5. Panel installer (Tauri NSIS) -------------------------------------------------------
Step "Panel installer (Tauri NSIS)"
$Release = Join-Path $RepoRoot "target\release"
$Resources = [ordered]@{}
$Resources[$Msix.Replace('\', '/')] = "DeskRemote-Menu.msix"
$Resources[$CerFile.Replace('\', '/')] = "DeskRemote-Menu.cer"
$Resources[(Join-Path $Release "desk_remote_menu.dll").Replace('\', '/')] = "desk_remote_menu.dll"
$Overlay = @{
    bundle = @{
        resources = $Resources
        windows   = @{
            nsis = @{
                installMode             = "both"
                languages               = @("Turkish", "English")
                displayLanguageSelector = $true
                installerIcon           = "icons/icon.ico"
                installerHooks          = (Join-Path $RepoRoot "packaging\panel-hooks.nsh").Replace('\', '/')
            }
        }
    }
}
$OverlayFile = Join-Path $Work "tauri-overlay.json"
[IO.File]::WriteAllText($OverlayFile, ($Overlay | ConvertTo-Json -Depth 8), (New-Object Text.UTF8Encoding $false))
Push-Location (Join-Path $RepoRoot "apps\desk-panel")
try {
    Run "tauri build" { & cargo tauri build --bundles nsis --config $OverlayFile | Out-Host }
} finally {
    Pop-Location
}
$PanelBuilt = Get-ChildItem (Join-Path $Release "bundle\nsis") -Filter "*_${Version}_x64-setup.exe" |
    Sort-Object LastWriteTime -Descending | Select-Object -First 1
if (-not $PanelBuilt) { throw "Tauri did not produce the panel installer" }
$PanelOut = Join-Path $Dist "Desk-Remote-Panel-Setup-$Version.exe"
Copy-Item $PanelBuilt.FullName $PanelOut -Force

# ---- 6. Agent installer (NSIS) -------------------------------------------------------------
Step "Agent installer (NSIS)"
$MakeNsis = Join-Path $env:LOCALAPPDATA "tauri\NSIS\makensis.exe"
if (-not (Test-Path $MakeNsis)) { throw "makensis not found at $MakeNsis (the Tauri build downloads it)" }
$AgentOut = Join-Path $Dist "Desk-Remote-Ajan-Setup-$Version.exe"
$AgentExe = Join-Path $Release "DeskRemote-Ajan.exe"
$IconPath = Join-Path $RepoRoot "apps\desk-service\icons\icon.ico"
Run "makensis" {
    & $MakeNsis /V2 "/DVERSION=$Version" "/DEXE_PATH=$AgentExe" "/DICON_PATH=$IconPath" "/DOUT_FILE=$AgentOut" `
        "/X!addincludedir `"$Gen`"" (Join-Path $RepoRoot "packaging\agent.nsi") | Out-Host
}

# ---- 7. Report -----------------------------------------------------------------------------
Step "Result"
$Sums = foreach ($f in @($PanelOut, $AgentOut)) {
    $item = Get-Item $f
    $hash = (Get-FileHash $f -Algorithm SHA256).Hash.ToLower()
    Write-Host ("{0}  {1,12:N0} bytes  sha256 {2}" -f $item.Name, $item.Length, $hash) -ForegroundColor Green
    "$hash  $($item.Name)"
}
[IO.File]::WriteAllLines((Join-Path $Dist "SHA256SUMS.txt"), $Sums)
Write-Host "Installers are not code-signed: Windows SmartScreen warns on first run (More info > Run anyway)." -ForegroundColor Yellow
